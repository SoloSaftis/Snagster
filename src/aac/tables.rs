/// One spectral codebook.
pub struct Codebook {
    /// Values per codeword (4 or 2; 0 for the zero book).
    pub dim: usize,
    /// Signed books code the sign in the codeword, unsigned ones add a sign bit per value.
    pub signed: bool,
    /// Largest absolute value the book codes (the escape book: 8191).
    pub lav: i32,
    modulo: i32,
    pub codes: &'static [u32],
    pub bits: &'static [u8],
}

impl Codebook {
    const fn new(dim: usize, signed: bool, lav: i32, modulo: i32, codes: &'static [u32], bits: &'static [u8]) -> Self {
        Self { dim, signed, lav, modulo, codes, bits }
    }

    fn escape(&self) -> bool {
        self.modulo == 17
    }

    /// Codeword index of `t` and the bits that follow the codeword (signs, escapes), or None
    /// when a value is too big for this book.
    pub fn index(&self, t: &[i32]) -> Option<(usize, usize)> {
        let mut idx = 0i32;
        let mut extra = 0;
        for &v in t {
            let a = v.abs();
            if a > self.lav {
                return None;
            }
            let d = if self.signed {
                v + (self.modulo - 1) / 2
            } else {
                if a != 0 {
                    extra += 1;
                }
                if self.escape() && a >= 16 {
                    extra += 2 * (31 - a.leading_zeros() as usize - 4) + 5;
                    16
                } else {
                    a
                }
            };
            idx = idx * self.modulo + d;
        }
        Some((idx as usize, extra))
    }

    /// Bits of a tuple of zeros.
    pub fn zero_bits(&self) -> usize {
        if self.dim == 0 {
            return 0;
        }
        let zero = [0i32; 4];
        self.index(&zero[..self.dim]).map(|(i, _)| self.bits[i] as usize).unwrap_or(0)
    }

    /// Write one tuple: codeword, sign bits, escape sequences.
    pub fn write(&self, w: &mut BitWriter, t: &[i32]) {
        let (idx, _) = self.index(t).expect("value fits the codebook");
        w.put(self.codes[idx], self.bits[idx] as u32);
        if self.signed {
            return;
        }
        for &v in t {
            if v != 0 {
                w.put((v < 0) as u32, 1);
            }
        }
        if self.escape() {
            for &v in t {
                let a = v.unsigned_abs();
                if a >= 16 {
                    let n = 31 - a.leading_zeros() - 4;
                    w.put(((1u32 << n) - 1) << 1, n + 1);
                    w.put(a - (1 << (n + 4)), n + 4);
                }
            }
        }
    }
}

